import { createServer } from "vite";
import { writeFileSync } from "node:fs";

const vite = await createServer({
  root: process.cwd(),
  server: { middlewareMode: true },
  appType: "custom",
  logLevel: "error",
});

try {
  const { DEFAULT_VERIFIED_LOADSTRING_URL, generateFullKeySystemScript } = await vite.ssrLoadModule("/src/lib/scriptGenerator.ts");
  const output = generateFullKeySystemScript(
    [
      {
        id: "game-1",
        name: "San Diego Border Roleplay",
        imageUrl: "https://raw.githubusercontent.com/Yousoterium/Sotarium/main/images/game1.png",
        placeId: "136020512003847",
        scriptUrl: "",
      },
      {
        id: "game-2",
        name: "Second Game",
        imageUrl: "https://example.com/second-game.png",
        placeId: "987654321",
        scriptUrl: "https://example.com/second-game.lua",
      },
    ],
    undefined,
    ""
  );

  writeFileSync("/tmp/sotarium-generated-runtime.lua", output);
  const required = [
    'local ContentFrame = Instance.new("Frame")',
    'local SubmitButton = Instance.new("TextButton")',
    'local GetKeyButton = Instance.new("TextButton")',
    'local JoinDiscordButton = Instance.new("TextButton")',
    'local function clearExistingSotariumGui()',
    'ScreenGui.DisplayOrder = 2147483647',
    'Generated by /add: complete home GUI build 2026.08.26.2',
    'Second Game',
    `loadstring(game:HttpGet(\\"${DEFAULT_VERIFIED_LOADSTRING_URL}\\"))()`,
  ];
  const missing = required.filter((snippet) => !output.includes(snippet));
  const report = {
    characters: output.length,
    lines: output.split("\n").length,
    hasHomeScreen: output.includes('local ContentFrame = Instance.new("Frame")'),
    containsSupportedGamesUi: /SupportedGamesButton|SupportedGamesPanel|SupportedGrid|GamesOverlay|GamesImage/.test(output),
    loadstringRunsAfterVerification: output.indexOf("if isValidKey then") < output.indexOf("local payload = matchedScript"),
    missing,
  };
  console.log(JSON.stringify(report, null, 2));
  if (report.characters < 1500 || !report.hasHomeScreen || report.containsSupportedGamesUi || !report.loadstringRunsAfterVerification || missing.length > 0) {
    process.exitCode = 1;
  }
} finally {
  await vite.close();
}
