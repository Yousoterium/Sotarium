-- ── File Storage Constants ─────────────────────────────────────
local KEY_FILE = "SotariumKey.txt"

local function canRead() return type(readfile) == "function" or type(read_file) == "function" end
local function canWrite() return type(writefile) == "function" or type(write_file) == "function" end
local function fileExists(path)
    if type(isfile) == "function" then return isfile(path) end
    if type(is_file) == "function" then return is_file(path) end
    return false
end

local function getSavedKey()
    if not canRead() then return nil end
    if fileExists(KEY_FILE) then
        local ok, content = pcall(readfile or read_file, KEY_FILE)
        if ok and type(content) == "string" and #content > 0 then
            return content:gsub("^%s*(.-)%s*$", "%1")
        end
    end
    return nil
end

local function saveKey(key)
    if not canWrite() or not key or #key == 0 then return end
    pcall(writefile or write_file, KEY_FILE, key)
end

-- ── Countdown / Time Formatter ────────────────────────────────
local function formatTimeRemaining(seconds)
    if not seconds or seconds <= 0 then return "Active" end
    local h = math.floor(seconds / 3600)
    local m = math.floor((seconds % 3600) / 60)
    local s = math.floor(seconds % 60)
    if h > 0 then
        return string.format("%dh %dm %ds left", h, m, s)
    elseif m > 0 then
        return string.format("%dm %ds left", m, s)
    else
        return string.format("%ds left", s)
    end
end

-- Universal Safe GUI Parent Resolver
local function getSafeGuiParent()
    if gethui then
        local success, res = pcall(gethui)
        if success and res then return res end
    end
    local hasCoreGui, core = pcall(function()
        return game:GetService("CoreGui")
    end)
    if hasCoreGui and core then
        local canWrite = pcall(function()
            local f = Instance.new("Folder")
            f.Parent = core
            f:Destroy()
        end)
        if canWrite then return core end
    end
    local lp = Players.LocalPlayer or Players:GetPropertyChangedSignal("LocalPlayer"):Wait() or Players.PlayerAdded:Wait()
    return lp:WaitForChild("PlayerGui", 5) or lp.PlayerGui
end

