-- Verification Engine
-- ===========================================
local KEY_VERIFY_URL = "https://sotarium.vercel.app/api/verify-key"

local function verifyKeyRemote(keyToVerify)
    local normalized = keyToVerify:gsub("%s+", ""):upper()
    if normalized == "" then
        return false, "Please enter a key", nil
    end

    local player = Players.LocalPlayer
    if not player then
        return false, "Roblox account unavailable", nil
    end

    local requestOptions = {
        Url = KEY_VERIFY_URL,
        Method = "POST",
        Headers = { ["Content-Type"] = "application/json" },
        Body = HttpService:JSONEncode({
            key = normalized,
            roblox_id = tostring(player.UserId),
            roblox_username = tostring(player.Name)
        })
    }

    local verifyGetUrl = KEY_VERIFY_URL
        .. "?key=" .. HttpService:UrlEncode(normalized)
        .. "&roblox_id=" .. HttpService:UrlEncode(tostring(player.UserId))
        .. "&roblox_username=" .. HttpService:UrlEncode(tostring(player.Name))

    local ok, response = pcall(function()
        if syn and syn.request then
            return syn.request(requestOptions)
        elseif http and http.request then
            return http.request(requestOptions)
        elseif http_request then
            return http_request(requestOptions)
        elseif request then
            return request(requestOptions)
        elseif HttpService and type(HttpService.GetAsync) == "function" then
            return { StatusCode = 200, Body = HttpService:GetAsync(verifyGetUrl) }
        elseif game and type(game.HttpGet) == "function" then
            return { StatusCode = 200, Body = game:HttpGet(verifyGetUrl, true) }
        end
        return nil
    end)

    if not ok or not response or response.StatusCode ~= 200 or type(response.Body) ~= "string" then
        return false, "Could not verify key. Please try again.", nil
    end

    local decodedOk, result = pcall(function()
        return HttpService:JSONDecode(response.Body)
    end)

    if not decodedOk or type(result) ~= "table" then
        return false, "Could not verify key. Please try again.", nil
    end

    if result.valid == true then
        return true, result.message or "Access granted", result.remaining_seconds
    end

    return false, result.message or "Key Invalid", nil
end

